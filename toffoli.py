import numpy as np
from qiskit import QuantumCircuit
from qiskit.quantum_info import Operator
from qiskit.circuit.library import CCXGate

# 1. Initialize the 3-qubit circuit
# Qubit 0 and 1 are the Controls, Qubit 2 is the Target
qc = QuantumCircuit(3)

# 2. Build the mathematically correct Toffoli decomposition
qc.h(2)         # Hadamard on Target
qc.cx(1, 2)     # CNOT (Control 1, Target 2)
qc.tdg(2)       # T-dagger on Target
qc.cx(0, 2)     # CNOT (Control 0, Target 2)
qc.t(2)         # T on Target
qc.cx(1, 2)     # CNOT (Control 1, Target 2)
qc.tdg(2)       # T-dagger on Target
qc.cx(0, 2)     # CNOT (Control 0, Target 2)
qc.t(1)         # T on Control 1
qc.t(2)         # T on Target
qc.h(2)         # Hadamard on Target
qc.cx(0, 1)     # CNOT (Control 0, Target 1)
qc.t(0)         # T on Control 0
qc.tdg(1)       # T-dagger on Control 1
qc.cx(0, 1)     # CNOT (Control 0, Target 1)

# 3. Extract the exact 8x8 Toffoli matrix using Qiskit's built-in gate
exact_toffoli = Operator(CCXGate()).data

# 4. Extract the matrix of the circuit we just built
constructed = Operator(qc).data

# 5. Account for the global phase (fundamental to quantum mechanics)
# Divide the first non-zero diagonal element to find the phase factor
phase = constructed[0, 0] / exact_toffoli[0, 0]

# 6. Verify if the matrices match
is_match = np.allclose(constructed / phase, exact_toffoli)

print(f"Does the corrected circuit equal the Toffoli gate? {is_match}")

# Print the exact Toffoli matrix (cleaned up for readability)
print("\n--- Exact Toffoli Matrix (8x8) ---")
print(np.round(np.real(exact_toffoli), 2))

# Print the matrix built by the circuit
print("\n--- Constructed Matrix from Circuit ---")
print(np.round(np.real(constructed), 2))